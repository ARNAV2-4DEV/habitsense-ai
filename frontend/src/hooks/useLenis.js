import { useEffect } from 'react'
import Lenis from 'lenis'

/**
 * Smooth-scrolls the document. Skipped entirely when the OS asks for
 * reduced motion -- this is a stylistic nicety, not a functional
 * requirement, so it shouldn't override an accessibility preference.
 */
export function useLenis() {
  useEffect(() => {
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return

    const lenis = new Lenis({
      duration: 1.05,
      easing: (t) => 1 - Math.pow(1 - t, 3),
      smoothWheel: true,
    })

    let rafId
    function raf(time) {
      lenis.raf(time)
      rafId = requestAnimationFrame(raf)
    }
    rafId = requestAnimationFrame(raf)

    return () => {
      cancelAnimationFrame(rafId)
      lenis.destroy()
    }
  }, [])
}
